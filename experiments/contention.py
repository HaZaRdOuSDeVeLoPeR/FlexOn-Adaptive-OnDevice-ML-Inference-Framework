"""Independent resource-contention controller for FlexOn experiments.

This module deliberately knows nothing about ``flexon_online`` or benchmark
measurement.  It only creates and removes external CPU/GPU load so that a
separate notebook can control the execution environment.

CPU contention is generated by busy worker processes. GPU contention is
command-based: the caller supplies a long-running GPU workload command. This
keeps the harness independent of a particular CUDA Python framework.
"""

from __future__ import annotations

from dataclasses import dataclass, field
import multiprocessing as mp
import os
import signal
import subprocess
import time
from typing import Optional, Sequence


ContentionKind = str


@dataclass(frozen=True)
class ContentionSpec:
    """Describe one external contention environment.

    Parameters
    ----------
    cpu_workers:
        Number of CPU cores intentionally saturated by busy workers. ``0``
        disables CPU contention.
    gpu_command:
        Long-running command that consumes GPU resources. The command should
        remain alive until terminated by the session. ``None`` disables GPU
        contention.
    gpu_workers:
        Number of independent GPU workload processes to launch. This is useful
        when the supplied GPU workload scales approximately linearly with the
        number of processes.
    startup_delay_seconds:
        Time allowed for contention processes to become active before the
        experiment starts.
    label:
        Optional human-readable label stored by the notebook as metadata.
    """

    cpu_workers: int = 0
    gpu_command: Optional[tuple[str, ...]] = None
    gpu_workers: int = 1
    startup_delay_seconds: float = 0.5
    label: str = "none"

    def __post_init__(self) -> None:
        if self.cpu_workers < 0:
            raise ValueError("cpu_workers cannot be negative")
        if self.gpu_workers <= 0:
            raise ValueError("gpu_workers must be greater than zero")
        if self.gpu_command is not None and not self.gpu_command:
            raise ValueError("gpu_command cannot be empty")
        if self.startup_delay_seconds < 0:
            raise ValueError("startup_delay_seconds cannot be negative")
        if not self.label.strip():
            raise ValueError("label cannot be empty")

    @property
    def enabled(self) -> bool:
        return self.cpu_workers > 0 or self.gpu_command is not None

    @property
    def kind(self) -> ContentionKind:
        if self.cpu_workers > 0 and self.gpu_command is not None:
            return "both"
        if self.cpu_workers > 0:
            return "cpu"
        if self.gpu_command is not None:
            return "gpu"
        return "none"

    @classmethod
    def none(
        cls, *, label: str = "none", startup_delay_seconds: float = 0.5
    ) -> "ContentionSpec":
        return cls(label=label, startup_delay_seconds=startup_delay_seconds)

    @classmethod
    def cpu(
        cls,
        workers: int,
        *,
        label: str = "cpu",
        startup_delay_seconds: float = 0.5,
    ) -> "ContentionSpec":
        return cls(
            cpu_workers=workers,
            label=label,
            startup_delay_seconds=startup_delay_seconds,
        )

    @classmethod
    def gpu(
        cls,
        command: Sequence[str],
        *,
        workers: int = 1,
        label: str = "gpu",
        startup_delay_seconds: float = 0.5,
    ) -> "ContentionSpec":
        return cls(
            gpu_command=tuple(command),
            gpu_workers=workers,
            label=label,
            startup_delay_seconds=startup_delay_seconds,
        )

    @classmethod
    def both(
        cls,
        *,
        cpu_workers: int,
        gpu_command: Sequence[str],
        gpu_workers: int = 1,
        label: str = "both",
        startup_delay_seconds: float = 0.5,
    ) -> "ContentionSpec":
        return cls(
            cpu_workers=cpu_workers,
            gpu_command=tuple(gpu_command),
            gpu_workers=gpu_workers,
            label=label,
            startup_delay_seconds=startup_delay_seconds,
        )


@dataclass
class ContentionSession:
    """Own and clean up all processes belonging to one contention interval."""

    spec: ContentionSpec
    _cpu_processes: list[mp.Process] = field(default_factory=list, init=False)
    _gpu_processes: list[subprocess.Popen] = field(default_factory=list, init=False)
    _started: bool = field(default=False, init=False)

    def start(self) -> "ContentionSession":
        if self._started:
            raise RuntimeError("contention session is already started")

        self._cpu_processes = []
        self._gpu_processes = []

        if self.spec.cpu_workers:
            context = mp.get_context("spawn")
            for _ in range(self.spec.cpu_workers):
                process = context.Process(target=_cpu_contention_worker, daemon=True)
                process.start()
                self._cpu_processes.append(process)

        if self.spec.gpu_command is not None:
            for _ in range(self.spec.gpu_workers):
                self._gpu_processes.append(_start_gpu_command(self.spec.gpu_command))

        self._started = True
        if self.spec.startup_delay_seconds:
            time.sleep(self.spec.startup_delay_seconds)
        return self

    def stop(self) -> None:
        if not self._started:
            return

        for process in self._cpu_processes:
            if process.is_alive():
                process.terminate()
        for process in self._cpu_processes:
            process.join(timeout=1.0)
            if process.is_alive():
                process.kill()
                process.join(timeout=1.0)

        for process in self._gpu_processes:
            _terminate_process_group(process)

        self._cpu_processes.clear()
        self._gpu_processes.clear()
        self._started = False

    def __enter__(self) -> "ContentionSession":
        return self.start()

    def __exit__(self, exc_type, exc_value, traceback) -> None:
        self.stop()

    @property
    def cpu_processes(self) -> tuple[mp.Process, ...]:
        return tuple(self._cpu_processes)

    @property
    def gpu_processes(self) -> tuple[subprocess.Popen, ...]:
        return tuple(self._gpu_processes)


def run_with_contention(spec: ContentionSpec, callback):
    """Run ``callback`` while the requested contention is active."""
    with ContentionSession(spec):
        return callback()


def _cpu_contention_worker() -> None:
    """Consume one CPU core until the parent terminates this process."""
    value = 0x12345678
    while True:
        value = ((value * 1664525) + 1013904223) & 0xFFFFFFFF
        value ^= value >> 13


def _start_gpu_command(command: Sequence[str]) -> subprocess.Popen:
    kwargs = {
        "stdin": subprocess.DEVNULL,
        "stdout": subprocess.DEVNULL,
        "stderr": subprocess.DEVNULL,
        "text": True,
    }
    if os.name == "posix":
        kwargs["start_new_session"] = True
    return subprocess.Popen(list(command), **kwargs)


def _terminate_process_group(process: subprocess.Popen) -> None:
    if process.poll() is not None:
        return

    if os.name == "posix":
        try:
            os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            return
        try:
            process.wait(timeout=1.0)
            return
        except subprocess.TimeoutExpired:
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                return
            process.wait(timeout=1.0)
    else:
        process.terminate()
        try:
            process.wait(timeout=1.0)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait(timeout=1.0)
